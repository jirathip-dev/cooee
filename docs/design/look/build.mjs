// #7: build sprites/<theme>.svg, the few sprites a chat needs from each herdsman theme, as <symbol>s under cooee's own
// ids (so a page uses `#s-<id>` whatever the theme). Farm and kitchen come from herdsman's assets/themes/<name>/sprites.svg,
// garden from herdsman#423's art.mjs (branch design-423). Usage, from this folder:
//   node build.mjs <herdsman checkout> <herdsman design-423 checkout>
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [hm, g423] = process.argv.slice(2);
if (!hm || !g423) { console.error('usage: node build.mjs <herdsman> <herdsman design-423>'); process.exit(2); }
const out = new URL('sprites/', import.meta.url);
mkdirSync(out, { recursive: true });
mkdirSync(new URL('icons/', import.meta.url), { recursive: true });

// cooee id → the theme's sprite. edit/read/run: the tool the agent runs (ACP tool_call kind: edit → impl, read/search/
// fetch → rev, execute → fix); idle: a thread at rest; done/needs/fail: the turn's end states; merged: the turn-done
// moment; loading and empty: the 132 × 100 figures (the loading overlay, an empty thread list).
const PICK = {
  farm: { edit: 'row-plough', read: 'row-vet', run: 'row-anvil', idle: 'row-graze', done: 'row-stable', needs: 'row-bale-red',
    merged: 'row-jump', fail: 'row-refuse', loading: 'horse-working', empty: 'horse-graze' },
  kitchen: { edit: 'row-cook', read: 'row-taste', run: 'row-chop', idle: 'row-wait', done: 'row-serve', needs: 'row-bell',
    merged: 'row-serve', fail: 'row-back', loading: 'chef-cook', empty: 'chef-wait' },
};
// #115: Scene's 132 × 100 poses (`s-scene-<pose>`): the theme's vector figures, never a row sprite blown up. edit: the
// impl action; idle, done, needs: herdsman's poses; merged: the merged moment; fail: the blocked pose.
const SCENE = {
  farm: { edit: 'horse-plough', idle: 'horse-graze', done: 'horse-done', needs: 'horse-blocked', merged: 'jump-over',
    fail: 'horse-blocked' },
  kitchen: { edit: 'chef-cook', idle: 'chef-wait', done: 'chef-serve', needs: 'chef-bell', merged: 'order-up',
    fail: 'chef-bell' },
};
// The big figures' coats, as herdsman's loading overlay and kitchen look A set them.
const COAT = { farm: '--c:#c89a56;--d:#a37a3c;--m:#e8dcc0;--b:#efe7dc;--fk:#58a6ff', kitchen: '--fk:#58a6ff' };

for (const [theme, ids] of Object.entries(PICK)) {
  const src = readFileSync(join(hm, `assets/themes/${theme}/sprites.svg`), 'utf8');
  let s = '';
  for (const [id, sid] of [...Object.entries(ids), ...Object.entries(SCENE[theme]).map(([k, v]) => [`scene-${k}`, v])]) {
    const line = src.split('\n').find(l => l.startsWith(`<g id="${sid}"`));
    if (!line) throw new Error(`${theme}: no sprite ${sid}`);
    const g = line.replace(` id="${sid}"`, '');
    // A row sprite is 16 sprite px wide: crop its viewBox to them, as herdsman's serve.js does (#281).
    const m = /(?:translate\(([\d.]+)[ ,][^)]*\)\s*)?scale\(([\d.]+)\)/.exec(g);
    const vb = sid.startsWith('row-') ? `${(m && m[1]) || 0} 0 ${16 * (m ? +m[2] : 8.25)} 100` : '0 0 132 100';
    s += `<symbol id="s-${id}" viewBox="${vb}">${sid.startsWith('row-') ? g : `<g style="${COAT[theme]}">${g}</g>`}</symbol>\n`;
  }
  writeFileSync(new URL(`${theme}.svg`, out), wrap(theme, s));
}

// Garden: the 24 × 24 row sprites by action and kind, and two keeper-and-plant figures drawn from art.mjs's maps.
const art = await import(join(g423, 'docs/design/garden/art.mjs'));
const sym = (id, vb, body) => `<symbol id="s-${id}" viewBox="${vb}" shape-rendering="crispEdges">${body}</symbol>\n`;
const R = art.rows(), look = `${art.style(0, 'l')};${art.sv('monstera')}`;
const GROW = { edit: 'water', read: 'inspect', run: 'prune', idle: 'idle', done: 'done', needs: 'thirsty', merged: 'sold', fail: 'fall' };
let s = '';
for (const [id, k] of Object.entries(GROW)) s += sym(id, '0 0 24 24', `<g style="${look}">${art.draw(R[k], 1)}</g>`);
const fig = (act, sp, stage) => `<g style="${art.sv(sp)}">${art.draw(art.plant(sp, stage))}</g><g style="${art.style(0, 'l')}">${art.draw(art.ACTIONS[act]())}</g>`;
s += sym('loading', '0 0 132 100', fig('water', 'monstera', 'impl')) + sym('empty', '0 0 132 100', fig('idle', 'pothos', 'ready'));
writeFileSync(new URL('garden.svg', out), wrap('garden', s));

// The theme icons (192 px), shown on the look sheet's THEME tiles. Farm is herdsman's board icon.
for (const [t, f] of Object.entries({ farm: join(hm, 'assets/icon-192.png'), kitchen: join(hm, 'assets/themes/kitchen/icon-192.png'),
  terminal: join(hm, 'assets/themes/terminal/icon-192.png'), garden: join(g423, 'docs/design/garden/icon/icon-192.png') }))
  copyFileSync(f, new URL(`icons/${t}.png`, import.meta.url));

function wrap(theme, body) {
  return `<svg xmlns="http://www.w3.org/2000/svg"><!-- #7: generated by build.mjs from herdsman's ${theme} theme; do not edit. -->\n${body}</svg>\n`;
}
console.log('sprites: farm kitchen garden · icons: 4');
