import { chromium } from "@playwright/test";
import fs from "node:fs";
const out = process.env.OUT, base = `http://127.0.0.1:${process.env.P}`;
const browser = await chromium.launch();
const pair = await browser.newPage({ baseURL: base });
await pair.goto("/");
console.log("unpaired / ->", new URL(pair.url()).pathname);
await pair.getByLabel("pairing code").fill(fs.readFileSync(`${out}/code`, "utf8").trim());
await pair.getByRole("button", { name: "pair" }).click();
await pair.waitForURL(/\/$/, { waitUntil: "commit" });
await pair.context().storageState({ path: `${out}/state.json` });
console.log("paired ->", new URL(pair.url()).pathname);
const titles = async (page) => (await page.locator(".fc .tr .tt").allInnerTexts()).join(" | ");
const checked = async (page) => page.locator("#chips [aria-checked=true]").innerText();
const pages = {};
for (const w of [390, 1440]) {
  const ctx = await browser.newContext({ baseURL: base, viewport: { width: w, height: w === 390 ? 844 : 900 }, storageState: `${out}/state.json` });
  const page = await ctx.newPage();
  pages[w] = page;
  const shot = async (name, ready) => {
    await ready.waitFor();
    await page.screenshot({ path: `${out}/${w}-${name}.png`, fullPage: true });
    console.log(`${w} ${name} ok`);
  };
  await page.goto("/");
  await shot("threads", page.locator(".fc .tr").first());
  console.log(`${w} All: chip=${await checked(page)} rows=[${await titles(page)}]`);
  console.log(`${w} All: lane meta=`, await page.locator(".fc .tr", { hasText: "cooee #33" }).locator(".ta").innerText());
  await page.locator("#chips").getByRole("radio", { name: "Workflow" }).click();
  await page.waitForFunction(() => document.querySelector("#chips [aria-checked=true]")?.textContent.trim() === "Workflow");
  await shot("workflow", page.locator(".fc .tr").first());
  console.log(`${w} Workflow: chip=${await checked(page)} open rows=[${(await page.locator(".fc > .tr .tt").allInnerTexts()).join(" | ")}] metas=[${(await page.locator(".fc > .tr .ta").allInnerTexts()).join(" | ")}]`);
  console.log(`${w} Workflow: card head=`, (await page.locator(".fc .fh").allInnerTexts()).join(" / "), "fold=", await page.locator(".fc details summary").allInnerTexts(), "fold rows visible=", await page.locator(".fc details .tr").isVisible());
  console.log(`${w} overflow px=`, await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth));
  await page.reload();
  console.log(`${w} after reload: chip=${await checked(page)} rows=[${await titles(page)}]`);
  await page.locator(".fc details summary").click();
  await shot("workflow-done", page.locator(".fc details .tr"));
  console.log(`${w} done fold row=`, await page.locator(".fc details .tr").innerText());
  await page.locator("#chips").getByRole("radio", { name: "Chats" }).click();
  await page.waitForFunction(() => document.querySelector("#chips [aria-checked=true]")?.textContent.trim() === "Chats");
  await shot("chats", page.locator(".fc .tr").first());
  console.log(`${w} Chats: chip=${await checked(page)} cards=`, (await page.locator(".fc .fh b").allInnerTexts()).join(" / "), `rows=[${await titles(page)}]`);
  // the JSON list the script redraws from, under this device's chip
  console.log(`${w} GET /threads (Chats cookie):`, (await (await page.request.get("/threads")).text()).slice(0, 300));
  await page.locator("#chips").getByRole("radio", { name: "All" }).click();
  await page.waitForFunction(() => document.querySelector("#chips [aria-checked=true]")?.textContent.trim() === "All");
  await page.locator(".fc .tr", { hasText: "cooee #33" }).click();
  await shot("workflow-chat", page.locator("#msgs"));
  console.log(`${w} lane chat: url=${new URL(page.url()).pathname} h1=${await page.getByRole("heading", { level: 1 }).innerText()} ds=${await page.locator(".th .ds").innerText()}`);
  console.log(`${w} lane chat: link=${await page.getByRole("link", { name: "issue & PR" }).getAttribute("href")} close hidden=${await page.locator("#close").isHidden()} stop visible=${await page.locator("#pill .stop").isVisible()} reply enabled=${await page.getByRole("textbox", { name: "message" }).isEnabled()}`);
  console.log(`${w} lane chat msgs:`, JSON.stringify(await page.locator("#msgs").innerText()));
  await page.goto("/");
  await page.locator(".fc .tr", { hasText: "cooee #31" }).click();
  await shot("workflow-rev", page.locator("#msgs"));
  console.log(`${w} rev lane msgs:`, JSON.stringify(await page.locator("#msgs").innerText()));
  // recipe's other screens
  await page.goto("/#new");
  await shot("new", page.getByLabel("first message"));
  await page.goto(`/t/long-${w}`);
  await shot("chat", page.getByLabel("message", { exact: true }));
}
// Phone (AC4): open the running impl lane, stop it, reply into it and watch the reply stream.
const page = pages[390];
await page.goto("/");
await page.locator("#chips").getByRole("radio", { name: "Workflow" }).click();
await page.waitForFunction(() => document.querySelector("#chips [aria-checked=true]")?.textContent.trim() === "Workflow");
await page.locator(".fc .tr", { hasText: "cooee #33" }).click();
await page.locator("#msgs").waitFor();
console.log("390 phone: before stop st=", await page.locator("#st").innerText());
await page.locator("#pill .stop").click();
await page.waitForFunction(() => document.querySelector("#st")?.dataset.st !== "working", null, { timeout: 15000 });
await page.screenshot({ path: `${out}/390-workflow-stopped.png`, fullPage: true });
console.log("390 phone: after stop st=", await page.locator("#st").innerText(), "msgs=", JSON.stringify(await page.locator("#msgs").innerText()));
const box = page.getByRole("textbox", { name: "message" });
await box.fill("slow 6");
await page.getByRole("button", { name: "send" }).click();
await page.locator("#msgs", { hasText: "w2" }).waitFor({ timeout: 15000 });
await page.screenshot({ path: `${out}/390-workflow-streaming.png`, fullPage: true });
console.log("390 phone: mid-stream st=", await page.locator("#st").innerText(), "msgs=", JSON.stringify(await page.locator("#msgs").innerText()));
await page.locator("#msgs", { hasText: "w5" }).waitFor({ timeout: 15000 });
await page.locator("#pill .stop").click();
await page.locator("#msgs", { hasText: "streamed 6 words" }).waitFor({ timeout: 15000 });
await box.fill("hello from verify");
await page.getByRole("button", { name: "send" }).click();
await page.locator("#msgs", { hasText: "Hello" }).last().waitFor({ timeout: 15000 });
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/390-workflow-replied.png`, fullPage: true });
console.log("390 phone: after reply st=", await page.locator("#st").innerText(), "msgs=", JSON.stringify(await page.locator("#msgs").innerText()));
await browser.close();
